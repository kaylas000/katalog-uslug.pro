function displayLabel(raw) {
  return raw
    .replace(/^город федерального значения\s+/i, '')
    .replace(/\s*\([^)]*\)\s*/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const seen = new Set();
const regions = [];

for (const [code, raw] of FNS) {
  const label = displayLabel(raw);
  const slug = slugFromLabel(code, raw);
  if (seen.has(slug)) {
    throw new Error(`Дубликат slug «${slug}» для кода ${code}`);
  }
  seen.add(slug);
  regions.push({ slug, label, intro: introFor(label) });
}

regions.push({
  slug: 'rossiya',
  label: 'Вся Россия',
  intro:
    'Компании с федеральным охватом, доставкой по России или удалённой работой без привязки к одному субъекту РФ.',
});

regions.sort((a, b) => a.label.localeCompare(b.label, 'ru'));

if (!fs.existsSync(path.dirname(outPath))) {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
}
fs.writeFileSync(outPath, `${JSON.stringify(regions, null, 2)}\n`, 'utf8');
